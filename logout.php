<?php

session_start();

// Clear all session data, not just user_id, then destroy the session
// itself so nothing authenticated can be recovered afterward.
$_SESSION = [];

if (ini_get("session.use_cookies")) {
    $params = session_get_cookie_params();
    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );
}

session_destroy();

header("Location: login.php?logged_out=1");
exit();
